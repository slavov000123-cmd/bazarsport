import {readFileSync} from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={exports:{},URL,env:{OWNER_EMAIL:'owner@example.test'}};
vm.runInNewContext(ts.transpileModule(readFileSync('lib/owner.ts','utf8').replace(/^import .*;$/gm,''),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,context);
const {ownerFromRequest}=context.exports;
const headers={'oai-authenticated-user-id':'owner-id','oai-authenticated-user-email':'owner@example.test'};
assert.equal(ownerFromRequest(new Request('https://site.test/api/drafts')),null);
assert.equal(ownerFromRequest(new Request('https://site.test/api/drafts',{headers:{...headers,'oai-authenticated-user-email':'other@example.test'}})),null);
assert.equal(ownerFromRequest(new Request('https://site.test/api/drafts',{method:'POST',headers:{...headers,origin:'https://evil.test'}})),null);
assert.equal(ownerFromRequest(new Request('https://site.test/api/drafts',{method:'POST',headers:{...headers,'sec-fetch-site':'cross-site'}})),null);
assert.equal(ownerFromRequest(new Request('https://site.test/api/drafts',{method:'POST',headers:{...headers,origin:'https://site.test'}})),'owner-id');
context.env.OWNER_EMAIL='';assert.equal(ownerFromRequest(new Request('https://site.test/api/drafts',{headers})),null);
