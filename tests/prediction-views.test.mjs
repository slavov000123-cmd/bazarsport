import {readFileSync} from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={exports:{},Date,Intl,Map,Set};
vm.runInNewContext(ts.transpileModule(readFileSync('lib/prediction-views.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,context);
const {sofiaDay,todayPredictions,resultHistory}=context.exports;
const prediction=(id,...dates)=>({id,title:id,payload:{category:'elite',selections:dates.map(kickoff=>({kickoff,odds:1.5}))}});
const old=prediction('old','2026-11-20T20:00:00Z'),today=prediction('today','2026-11-21T12:00:00Z'),tomorrow=prediction('tomorrow','2026-11-22T12:00:00Z');
const overnight=prediction('overnight','2026-11-21T22:30:00Z');
const mixed=prediction('mixed','2026-11-20T21:00:00Z','2026-11-21T12:00:00Z');
const all=[old,today,tomorrow,overnight,mixed];const snapshot=JSON.stringify(all);
assert.equal(sofiaDay('2026-11-21T21:59:59Z'),'2026-11-21');
assert.equal(sofiaDay('2026-11-21T22:00:00Z'),'2026-11-22');
assert.equal(sofiaDay('2026-07-01T21:00:00Z'),'2026-07-02');
assert.equal(sofiaDay('invalid'),'');
assert.equal(todayPredictions(all,'2026-11-21').map(p=>p.id).join(','),'today,mixed');
assert.equal(todayPredictions(all,'2026-11-22').map(p=>p.id).join(','),'tomorrow,overnight');
const groups=resultHistory(all,[],'2026-11-21');assert.equal(groups.length,1);assert.equal(groups[0].date,'2026-11-20');assert.equal(groups[0].slips[0].prediction.id,'old');assert.equal(groups[0].slips[0].result,undefined);
const next=resultHistory(all,[],'2026-11-22');assert.equal(next[0].date,'2026-11-21');assert.equal(next[0].slips.length,2);
const win={id:'result',title:'result',payload:{predictionId:'old',outcome:'WIN'}};
assert.equal(resultHistory(all,[win],'2026-11-21')[0].slips[0].result.payload.outcome,'WIN');
assert.equal(JSON.stringify(all),snapshot,'No deletion, mutation or changed combined odds');
const countryContext={exports:{}};
vm.runInNewContext(ts.transpileModule(readFileSync('lib/countries.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,countryContext);
const {teamCountry}=countryContext.exports;
assert.equal(teamCountry('Chelsea','GB-ENG'),teamCountry('Leeds','GB-ENG'));
assert.notEqual(teamCountry('France'),teamCountry('Turkey'));
assert.equal(teamCountry('Unknown club'),undefined);
console.log('PASS: Sofia midnight and DST, today-only picks, future exclusion, dated archive, mixed-day slips, verified outcomes and flag deduplication');

const settledToday={id:'settled',payload:{predictionId:'today',outcome:'WIN'}};
assert.equal(todayPredictions(all,'2026-11-21',[settledToday]).map(p=>p.id).join(','),'mixed');
assert.ok(resultHistory(all,[settledToday],'2026-11-21').some(g=>g.slips.some(s=>s.prediction.id==='today')));
console.log('PASS: approved settled slip moves from today to results without deleting history');
